import { CriteriaError, fixtureBytesMax, parseParserCriteria, sha256Hex, type ParserCriteriaV1 } from "./criteria.js";
import { compiledParserSpecs } from "./generated/registry.js";
import { parseParserSpec, ParserSpecError, type ParserSpecV1 } from "./spec.js";

export interface RegistryIssue {
  path: string;
  message: string;
}

export class RegistryError extends Error {
  readonly issues: ReadonlyArray<RegistryIssue>;

  constructor(issues: ReadonlyArray<RegistryIssue>) {
    super(issues.map((issue) => `${issue.path}: ${issue.message}`).join("\n"));
    this.name = "RegistryError";
    this.issues = issues;
  }
}

export interface DomainSourceFile {
  path: string;
  kind: "file" | "directory" | "symlink";
  text: string;
  byteLength: number;
}

const PARSER_ID = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const FIXTURE_NAME = /^[0-9a-f]{64}\.html$/;
const ID_MAX = 64;
const DOMAINS_ROOT = "src/parsers/domains";

interface OwnedSpec {
  spec: ParserSpecV1;
  path: string;
}

interface HostReservation {
  host: string;
  id: string;
  path: string;
}

export function disabledParserIds(raw: string | undefined): ReadonlySet<string> {
  const ids = new Set<string>();
  if (raw === undefined || raw.trim() === "") return ids;
  const issues: RegistryIssue[] = [];
  const parts = raw.split(",");
  for (let index = 0; index < parts.length; index += 1) {
    const id = parts[index]?.trim() ?? "";
    if (!id) continue;
    if (id.length > ID_MAX || !PARSER_ID.test(id)) {
      issues.push({
        path: `PIRATE_RADIO_DISABLED_PARSERS[${index}]`,
        message: `parser id "${id}" must be kebab-case. Use the directory name under src/parsers/domains.`,
      });
      continue;
    }
    ids.add(id);
  }
  if (issues.length > 0) throw new RegistryError(issues);
  return ids;
}

export function matchSpecs(
  specs: readonly ParserSpecV1[],
  url: URL,
  disabled: ReadonlySet<string>,
): ParserSpecV1 | undefined {
  const host = normalizeHost(url.hostname);
  const matches = specs.filter((spec) => {
    if (disabled.has(spec.id)) return false;
    if (!spec.hosts.includes(host)) return false;
    if (!spec.paths) return true;
    return spec.paths.prefixes.some((prefix) => prefixMatches(url.pathname, prefix));
  });
  if (matches.length > 1) {
    const ids = matches.map((spec) => spec.id).sort().join(" and ");
    throw new RegistryError([
      {
        path: "hosts",
        message: `host "${host}" matches ${ids}. Keep the host on one parser.`,
      },
    ]);
  }
  return matches[0];
}

export function matchParser(url: URL, disabled: ReadonlySet<string>): ParserSpecV1 | undefined {
  return matchSpecs(compiledParsers, url, disabled);
}

export function activeParsers(): readonly ParserSpecV1[] {
  return compiledParsers;
}

export function renderCompiledRegistry(specs: readonly ParserSpecV1[]): string {
  const ordered = [...specs].sort(byId);
  return `// Generated by scripts/parsers/generate-registry.ts. Do not edit.\nexport const compiledParserSpecs: readonly unknown[] = ${JSON.stringify(ordered, null, 2)};\n`;
}

export function compileDomainFiles(
  files: readonly DomainSourceFile[],
  isFirstPartyHost: (host: string) => boolean,
): { specs: ParserSpecV1[]; issues: RegistryIssue[] } {
  const issues: RegistryIssue[] = [];
  const groups = new Map<string, DomainSourceFile[]>();
  const seen = new Set<string>();

  for (const entry of files) {
    const relative = entry.path.replaceAll("\\", "/").replace(/^\.\//, "");
    const split = splitDomainPath(relative);
    if (!split || split.id.length > ID_MAX || !PARSER_ID.test(split.id)) {
      issues.push({
        path: domainFilePath(relative || entry.path),
        message: "domain directory names must be kebab-case. Rename the directory or remove it.",
      });
      continue;
    }
    if (seen.has(relative)) {
      issues.push({ path: domainFilePath(relative), message: "duplicate path. Keep one file." });
      continue;
    }
    seen.add(relative);
    const list = groups.get(split.id) ?? [];
    list.push({ ...entry, path: relative });
    groups.set(split.id, list);
  }

  const owned: OwnedSpec[] = [];
  const reservations: HostReservation[] = [];
  for (const [id, entries] of [...groups.entries()].sort((left, right) => compareText(left[0], right[0]))) {
    const parsed = parseDomain(id, entries, issues);
    if (parsed.spec) owned.push(parsed.spec);
    if (parsed.reservation) reservations.push(parsed.reservation);
  }

  const hostOwner = new Map<string, OwnedSpec>();
  for (const item of owned) {
    for (const host of item.spec.hosts) {
      if (isFirstPartyHost(host) || isFirstPartyHost(`www.${host}`)) {
        issues.push({
          path: item.path,
          message: `host "${host}" belongs to a built-in article source. Remove "${host}" from hosts.`,
        });
      }
      const owner = hostOwner.get(host);
      if (owner) {
        issues.push({
          path: item.path,
          message: `host "${host}" is already claimed by ${owner.path}. Keep the host on one parser.`,
        });
      } else {
        hostOwner.set(host, item);
      }
      const reserved = reservations.find((reservation) => reservation.host === host && reservation.id !== item.spec.id);
      if (reserved) {
        issues.push({
          path: item.path,
          message: `host "${host}" is reserved by ${reserved.path} for "${reserved.id}". Remove "${host}" from hosts or move this spec to ${reserved.id}.`,
        });
      }
    }
  }

  if (issues.length > 0) return { specs: [], issues: sortIssues(issues) };
  return { specs: owned.map((item) => item.spec).sort(byId), issues: [] };
}

function parseDomain(
  id: string,
  entries: readonly DomainSourceFile[],
  issues: RegistryIssue[],
): { spec?: OwnedSpec; reservation?: HostReservation } {
  let parserFile: DomainSourceFile | undefined;
  let criteriaFile: DomainSourceFile | undefined;
  const fixtures = new Map<string, DomainSourceFile>();

  for (const entry of entries) {
    const tail = splitDomainPath(entry.path)?.tail ?? "";
    const fullPath = domainFilePath(entry.path);
    if (entry.kind === "symlink") {
      issues.push({
        path: fullPath,
        message: "symlinks are not allowed. Replace the symlink with a regular file.",
      });
      continue;
    }
    if ((tail === "" || tail === "fixtures") && entry.kind === "directory") continue;
    if (tail === "parser.json" && entry.kind === "file") {
      parserFile = entry;
      continue;
    }
    if (tail === "criteria.json" && entry.kind === "file") {
      criteriaFile = entry;
      continue;
    }
    const fixtureName = tail.startsWith("fixtures/") ? tail.slice("fixtures/".length) : "";
    if (entry.kind === "file" && fixtureName && !fixtureName.includes("/") && FIXTURE_NAME.test(fixtureName)) {
      fixtures.set(fixtureName, entry);
      checkFixtureBytes(fullPath, fixtureName, entry, issues);
      continue;
    }
    const name = tail.split("/").at(-1) || entry.path;
    issues.push({
      path: fullPath,
      message: `domains may contain only parser.json, criteria.json, and fixtures/<sha256>.html. Remove ${name}.`,
    });
  }

  const specPath = domainFilePath(`${id}/parser.json`);
  const criteriaPath = domainFilePath(`${id}/criteria.json`);
  const spec = readSpec(id, parserFile, specPath, issues);
  const criteria = readCriteria(id, criteriaFile, criteriaPath, issues);
  if (criteria) {
    for (const example of criteria.examples) {
      const name = example.fixture.slice("fixtures/".length);
      if (!fixtures.has(name)) {
        issues.push({
          path: criteriaPath,
          message: `fixture "${example.fixture}" is missing. Add ${example.fixture} under ${id}/fixtures.`,
        });
      }
    }
  }
  if (spec && criteria && !spec.hosts.includes(criteria.host)) {
    issues.push({
      path: criteriaPath,
      message: `host "${criteria.host}" must be listed in ${specPath} hosts.`,
    });
  }
  return {
    spec: spec ? { spec, path: specPath } : undefined,
    reservation: criteria ? { host: criteria.host, id: criteria.parserId, path: criteriaPath } : undefined,
  };
}

function readSpec(
  id: string,
  entry: DomainSourceFile | undefined,
  path: string,
  issues: RegistryIssue[],
): ParserSpecV1 | undefined {
  if (!entry) return undefined;
  const parsed = readJson(entry, path, issues);
  if (parsed === undefined) return undefined;
  try {
    const spec = parseParserSpec(parsed);
    if (spec.id !== id) {
      issues.push({
        path,
        message: `id must equal the directory name "${id}". Set id to "${id}".`,
      });
      return undefined;
    }
    return spec;
  } catch (error) {
    if (error instanceof ParserSpecError) {
      for (const issue of error.issues) {
        issues.push({ path, message: `${issue.path}: ${issue.message}` });
      }
      return undefined;
    }
    throw error;
  }
}

function readCriteria(
  id: string,
  entry: DomainSourceFile | undefined,
  path: string,
  issues: RegistryIssue[],
): ParserCriteriaV1 | undefined {
  if (!entry) return undefined;
  const parsed = readJson(entry, path, issues);
  if (parsed === undefined) return undefined;
  try {
    const criteria = parseParserCriteria(parsed);
    if (criteria.parserId !== id) {
      issues.push({
        path,
        message: `parserId must equal the directory name "${id}". Set parserId to "${id}".`,
      });
      return undefined;
    }
    return criteria;
  } catch (error) {
    if (error instanceof CriteriaError) {
      for (const issue of error.issues) {
        issues.push({ path, message: `${issue.path}: ${issue.message}` });
      }
      return undefined;
    }
    throw error;
  }
}

function readJson(entry: DomainSourceFile, path: string, issues: RegistryIssue[]): unknown | undefined {
  try {
    return JSON.parse(entry.text) as unknown;
  } catch {
    issues.push({ path, message: "must be JSON. Fix the syntax." });
    return undefined;
  }
}

function checkFixtureBytes(path: string, fileName: string, entry: DomainSourceFile, issues: RegistryIssue[]) {
  if (entry.byteLength > fixtureBytesMax || Buffer.byteLength(entry.text) > fixtureBytesMax) {
    issues.push({
      path,
      message: `fixture is larger than ${fixtureBytesMax} bytes. Replace it with a redacted fixture of at most ${fixtureBytesMax} bytes.`,
    });
    return;
  }
  const actual = sha256Hex(entry.text);
  const named = fileName.slice(0, -".html".length);
  if (actual !== named) {
    issues.push({
      path,
      message: `fixture sha256 must equal the file name. Rename it to ${actual}.html.`,
    });
  }
}

function splitDomainPath(path: string): { id: string; tail: string } | undefined {
  if (!path || path.startsWith("/") || path.split("/").some((part) => part === "" || part === "." || part === "..")) {
    return undefined;
  }
  const slash = path.indexOf("/");
  if (slash === -1) return { id: path, tail: "" };
  return { id: path.slice(0, slash), tail: path.slice(slash + 1) };
}

function domainFilePath(relative: string): string {
  return `${DOMAINS_ROOT}/${relative}`;
}

function sortIssues(issues: readonly RegistryIssue[]): RegistryIssue[] {
  return [...issues].sort((left, right) => {
    if (left.path === right.path) return compareText(left.message, right.message);
    return compareText(left.path, right.path);
  });
}

function byId(left: { id: string }, right: { id: string }): number {
  return compareText(left.id, right.id);
}

function compareText(left: string, right: string): number {
  if (left < right) return -1;
  if (left > right) return 1;
  return 0;
}

function normalizeHost(hostname: string): string {
  const lower = hostname.toLowerCase().replace(/\.$/, "");
  return lower.startsWith("www.") ? lower.slice(4) : lower;
}

function prefixMatches(pathname: string, prefix: string): boolean {
  if (pathname === prefix) return true;
  const boundary = prefix.endsWith("/") ? prefix : `${prefix}/`;
  return pathname.startsWith(boundary);
}

function loadCompiled(rawSpecs: readonly unknown[]): readonly ParserSpecV1[] {
  return Object.freeze(
    rawSpecs.map((raw, index) => {
      try {
        return parseParserSpec(raw);
      } catch (error) {
        const message = error instanceof Error ? error.message : "invalid parser spec";
        throw new RegistryError([{ path: `compiledParserSpecs[${index}]`, message }]);
      }
    }),
  );
}

const compiledParsers = loadCompiled(compiledParserSpecs);
